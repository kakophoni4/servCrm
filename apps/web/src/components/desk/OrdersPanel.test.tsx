import {render,screen,fireEvent,cleanup,waitFor} from '@testing-library/react';
import {afterEach,expect,it,vi} from 'vitest';
import {OrdersPanel} from './OrdersPanel';
import {api,getStoredUser} from '@/lib/api';
vi.mock('./DeskLists.module.css',()=>({default:{}}));
vi.mock('next/navigation',()=>({useRouter:()=>({push:vi.fn()})}));
vi.mock('@/lib/api',()=>({api:vi.fn(),getStoredUser:vi.fn()}));
afterEach(()=>{cleanup();vi.clearAllMocks()});
it('combines appliance, status and text filters and resets appliance without losing status',async()=>{
 vi.mocked(getStoredUser).mockReturnValue({role:'OWNER'} as ReturnType<typeof getStoredUser>);
 const order=(id:string,typeTech:string,status:string)=>({id,publicId:id,typeTech,status,type:'NEW',sourceKind:'OUR',address:'Адрес',createdAt:new Date().toISOString(),client:{name:id,phoneNormalized:'79990000000'}});
 vi.mocked(api).mockImplementation(async path=>path==='/orders'?[order('Холодильник','ХД','WAITING'),order('Телевизор','ТВ','WAITING'),order('Закрытый ТВ','ТВ','DONE'),order('Отмена','ХД','CANCELLED_CC')]:[]);
 render(<OrdersPanel/>);
 fireEvent.click(screen.getByRole('button',{name:'В работе'}));
 await waitFor(()=>expect(screen.getByText('Найдено: 2')).toBeTruthy());
 fireEvent.change(screen.getByLabelText('Техника'),{target:{value:'ТВ'}});
 expect(screen.getByText('Найдено: 1')).toBeTruthy();
 expect(screen.queryByText('Холодильник')).toBeNull();
 fireEvent.change(screen.getByLabelText('Поиск заявок'),{target:{value:'не существует'}});
 expect(screen.getByText('Найдено: 0')).toBeTruthy();
 fireEvent.change(screen.getByLabelText('Поиск заявок'),{target:{value:''}});
 fireEvent.change(screen.getByLabelText('Техника'),{target:{value:''}});
 expect(screen.getByText('Найдено: 2')).toBeTruthy();
 fireEvent.click(screen.getByRole('button',{name:'Отменённые'}));
 expect(screen.getByText('Найдено: 1')).toBeTruthy();
 expect(screen.getAllByText('Отмена').length).toBeGreaterThan(0);
 fireEvent.click(screen.getByRole('button',{name:'Закрытые'}));
 expect(screen.getByText('Найдено: 1')).toBeTruthy();
 expect(screen.queryByText('Отмена')).toBeNull();
});
